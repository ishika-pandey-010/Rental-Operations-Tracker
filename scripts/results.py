#!/usr/bin/env python3
"""Generate the README Results table (CLAUDE.md rule 5: no metric typed by hand).

Reads:  docs/uat/test-cases.csv      UAT status per case
        docs/user-test.md            raw timings table (rows added only after real sessions)
        tests/, e2e/                 which UAT cases have an automated test (via docs_check)
Writes: the block between <!-- results:start --> and <!-- results:end --> in README.md

Usage:  python3 scripts/results.py          # rewrite README.md
        python3 scripts/results.py --check  # fail if README.md is stale
"""
import csv
import re
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
from docs_check import read_automated_tests  # noqa: E402

START, END = "<!-- results:start -->", "<!-- results:end -->"


def uat():
    with open(ROOT / "docs" / "uat" / "test-cases.csv", newline="") as f:
        cases = list(csv.DictReader(f))
    executed = [c for c in cases if c["status"] != "Not run"]
    passed = [c for c in executed if c["status"] == "Pass"]
    crit_high = [c for c in cases if c["priority"] in ("Critical", "High")]
    crit_high_pass = [c for c in crit_high if c["status"] == "Pass"]
    automated = {tc for tc, _, _ in read_automated_tests()}
    return {
        "total": len(cases),
        "executed": len(executed),
        "passed": len(passed),
        "failed": sum(1 for c in executed if c["status"] == "Fail"),
        "crit_high": len(crit_high),
        "crit_high_pass": len(crit_high_pass),
        "automated": sum(1 for c in cases if c["id"] in automated),
        "bugs": sorted({c["bug"] for c in cases if c["bug"].strip()}),
    }


def minutes(mmss):
    m, s = mmss.strip().split(":")
    return int(m) * 60 + int(s)


def fmt(seconds):
    return f"{int(seconds // 60)}:{int(round(seconds % 60)):02d}"


def user_test():
    text = (ROOT / "docs" / "user-test.md").read_text()
    section = text.split("## Raw data", 1)[1].split("\n## ", 1)[0]
    rows = []
    for line in section.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 4 and re.fullmatch(r"P\d+", cells[0]):
            rows.append(cells)
    if not rows:
        return None
    sheet = [minutes(r[2]) for r in rows]
    app = [minutes(r[3]) for r in rows]
    return {"n": len(rows), "sheet": statistics.median(sheet), "app": statistics.median(app)}


def block():
    u, t = uat(), user_test()
    if u["executed"]:
        uat_line = f"{u['executed']} of {u['total']} executed; {u['passed']} passed, {u['failed']} failed"
        gate = f"{u['crit_high_pass']} of {u['crit_high']} Critical/High cases passed"
    else:
        uat_line = f"Not run yet: 0 of {u['total']} executed (needs the hosted demo, OQ-16)"
        gate = f"0 of {u['crit_high']} Critical/High cases passed (UAT not run)"
    bugs = f"{len(u['bugs'])} logged in the UAT sheet" if u["bugs"] else "None logged in the UAT sheet yet"
    if t:
        timing = f"{fmt(t['sheet'])} → {fmt(t['app'])} (median of {t['n']})"
    else:
        timing = "Not run yet: no sessions in `docs/user-test.md` (OQ-18)"
    lines = [
        START,
        "<!-- Generated by scripts/results.py from docs/uat/test-cases.csv and docs/user-test.md. Run `make docs`; don't edit. -->",
        "",
        "| Metric | Value | Produced by |",
        "| --- | --- | --- |",
        f"| UAT cases executed / passed | {uat_line} | `docs/uat/test-cases.csv` |",
        f"| UAT exit gate (100% of Critical and High) | {gate} | `docs/uat/test-cases.csv` |",
        f"| UAT cases with an automated test | {u['automated']} of {u['total']} | test names in `tests/` and `e2e/` |",
        f"| Bugs found in UAT | {bugs} | `docs/uat/test-cases.csv` `bug` column |",
        f"| Median task time, spreadsheet → app | {timing} | `docs/user-test.md` |",
        END,
    ]
    return "\n".join(lines)


def main():
    readme = ROOT / "README.md"
    text = readme.read_text()
    if START not in text:
        print("README.md has no results block markers")
        sys.exit(1)
    new = re.sub(re.escape(START) + r".*?" + re.escape(END), block(), text, flags=re.S)
    if "--check" in sys.argv:
        if new != text:
            print("README Results are stale; run `make docs`")
            sys.exit(1)
        return
    readme.write_text(new)
    print("Wrote README.md Results")


if __name__ == "__main__":
    main()
